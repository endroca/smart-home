// Server serves the embedded UI, the JSON API and firmware files.
type Server struct {
	hub        *hub.Hub
	cfg        config.Config
	tuya       *service.Service
	midea      *mideasvc.Service
	store      *db.Store
	dispatcher *dispatch.Dispatcher
	voice      *voice.Service
	bus        *eventbus.Bus
}

// New creates the HTTP handler.
func New(h *hub.Hub, cfg config.Config, store *db.Store) *Server {
	return &Server{hub: h, cfg: cfg, store: store}
}

// Handler returns the root http.Handler.
func (s *Server) Handler() http.Handler {
	mux := http.NewServeMux()
	mux.HandleFunc("/api/health", s.health)
	mux.HandleFunc("/api/events", s.eventStream)
	mux.HandleFunc("/api/things", s.things)
	mux.HandleFunc("/api/things/", s.thingRoute)
	mux.HandleFunc("/api/firmware", s.firmware)
	mux.HandleFunc("/api/firmware/", s.firmwareByName)
	mux.HandleFunc("/firmware/", s.firmwareFile)
	s.tuyaRoutes(mux)
	s.mideaRoutes(mux)
	s.deviceRoutes(mux)
	s.automationRoutes(mux)
	s.voiceRoutes(mux)
	mux.Handle("/", webUIHandler())
	return mux
}

// webUIHandler serves the embedded UI (the compiled Svelte app). It fills in
// the PWA manifest content type (which the Go mime table does not know) and
// keeps the service worker uncached so a new version takes over on the next
// visit. The worker's precache manifest carries content hashes generated by
// vite-plugin-pwa, so cache invalidation follows the build automatically.
func webUIHandler() http.Handler {
	files := http.FileServer(http.FS(web.FS))
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch {
		case strings.HasSuffix(r.URL.Path, ".webmanifest"):
			w.Header().Set("Content-Type", "application/manifest+json")
		case r.URL.Path == "/sw.js":
			if r.Method != http.MethodGet && r.Method != http.MethodHead {
				methodNotAllowed(w)
				return
			}
			w.Header().Set("Cache-Control", "no-cache")
		}
		files.ServeHTTP(w, r)
	})
}

func (s *Server) health(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodGet {
		methodNotAllowed(w)
		return
	}
	body := s.hub.Health()
	// build fingerprints the embedded UI assets; /sw.js embeds the same value
	// in the cache name, so it is handy to confirm from the outside.
	body["build"] = web.BuildID()
	writeJSON(w, http.StatusOK, body)
}

func (s *Server) things(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodGet {
		methodNotAllowed(w)
		return
	}
	writeJSON(w, http.StatusOK, map[string]any{"ok": true, "things": s.hub.Snapshot()})
}

func (s *Server) thingRoute(w http.ResponseWriter, r *http.Request) {
	rest := strings.TrimPrefix(r.URL.Path, "/api/things/")
	parts := strings.Split(strings.Trim(rest, "/"), "/")
	if len(parts) == 0 || parts[0] == "" {
		writeError(w, http.StatusNotFound, "not_found", "thing is required")
		return
	}
	thing, err := url.PathUnescape(parts[0])
	if err != nil {
		writeError(w, http.StatusBadRequest, "invalid_thing", "invalid thing name")
		return
	}

	switch {
	case len(parts) == 1 && r.Method == http.MethodGet:
		t, ok := s.hub.Thing(thing)
		if !ok {
			writeError(w, http.StatusNotFound, "unknown_thing", "thing not found")
			return
		}
		writeJSON(w, http.StatusOK, map[string]any{"ok": true, "thing": t})
	case len(parts) == 2 && parts[1] == "commands" && r.Method == http.MethodPost:
		s.command(w, r, thing)
	case len(parts) == 2 && parts[1] == "events" && r.Method == http.MethodPost:
		s.ingest(w, r, thing)
	case len(parts) == 2 && parts[1] == "config" && (r.Method == http.MethodGet || r.Method == http.MethodPost):
		s.config(w, r, thing)
	case len(parts) == 2 && parts[1] == "learn" && r.Method == http.MethodPost:
		s.learn(w, r, thing)
	case len(parts) == 3 && parts[1] == "learn" && parts[2] == "cancel" && r.Method == http.MethodPost:
		s.learnCancel(w, r, thing)
	case len(parts) == 3 && parts[1] == "learn" && parts[2] == "status" && r.Method == http.MethodGet:
		s.learnStatus(w, r, thing)
	case len(parts) == 2 && parts[1] == "reboot" && r.Method == http.MethodPost:
		s.reboot(w, r, thing)
	case len(parts) == 2 && parts[1] == "diag" && r.Method == http.MethodGet:
		s.diag(w, r, thing)
	case len(parts) == 2 && parts[1] == "probe" && r.Method == http.MethodPost:
		s.probe(w, r, thing)
	case len(parts) == 2 && parts[1] == "ota" && r.Method == http.MethodPost:
		s.ota(w, r, thing)
	case len(parts) == 4 && parts[1] == "devices":
		deviceID, err := url.PathUnescape(parts[2])
		if err != nil {
			writeError(w, http.StatusBadRequest, "invalid_device", "invalid device id")
			return
		}
		switch parts[3] {
		case "state":
			if r.Method != http.MethodPost {
				methodNotAllowed(w)
				return
			}
			s.state(w, r, thing, deviceID)
		case "correct":
			if r.Method != http.MethodPost {
				methodNotAllowed(w)
				return
			}
			s.correct(w, r, thing, deviceID)
		default:
			writeError(w, http.StatusNotFound, "not_found", "route not found")
		}
	default:
		writeError(w, http.StatusNotFound, "not_found", "route not found")
	}
}

func (s *Server) state(w http.ResponseWriter, r *http.Request, thing, deviceID string) {
	var req struct {
		State map[string]any `json:"state"`
		Force bool           `json:"force"`
	}
	if err := decode(r, &req); err != nil {
		writeError(w, http.StatusBadRequest, "invalid_payload", err.Error())
		return
	}
	res, err := s.hub.SetState(r.Context(), thing, deviceID, req.State, req.Force)
	if err != nil {
		writeHubError(w, err)
		return
	}
	writeJSON(w, http.StatusOK, map[string]any{"ok": true, "result": res})
}

