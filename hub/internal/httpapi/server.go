func (s *Server) command(w http.ResponseWriter, r *http.Request, thing string) {
	var req struct {
		Action   string         `json:"action"`
		DeviceID string         `json:"id"`
		Command  string         `json:"command"`
		Name     string         `json:"name"`
		Config   map[string]any `json:"config"`
		State    map[string]any `json:"state"`
	}
	if err := decode(r, &req); err != nil {
		writeError(w, http.StatusBadRequest, "invalid_payload", err.Error())
		return
	}
	fields := map[string]any{}
	if req.DeviceID != "" {
		fields["id"] = req.DeviceID
	}
	if req.Command != "" {
		fields["command"] = req.Command
	}
	if req.Name != "" {
		fields["name"] = req.Name
	}
	if req.Config != nil {
		fields["config"] = req.Config
	}
	if req.State != nil {
		fields["state"] = req.State
	}
	res, err := s.hub.Command(r.Context(), thing, req.Action, fields)
	if err != nil {
		writeHubError(w, err)
		return
	}
	writeJSON(w, http.StatusOK, map[string]any{"ok": true, "result": res})
}

func (s *Server) config(w http.ResponseWriter, r *http.Request, thing string) {
	if r.Method == http.MethodGet {
		res, err := s.hub.ConfigGet(r.Context(), thing)
		if err != nil {
			writeHubError(w, err)
			return
		}
		writeJSON(w, http.StatusOK, map[string]any{"ok": true, "result": res})
		return
	}
	var raw map[string]any
	if err := decode(r, &raw); err != nil {
		writeError(w, http.StatusBadRequest, "invalid_payload", err.Error())
		return
	}
	cfgMap, _ := raw["config"].(map[string]any)
	if cfgMap == nil {
		// Accept the raw config object as a convenience.
		cfgMap = raw
	}
	if len(cfgMap) == 0 {
		writeError(w, http.StatusBadRequest, "invalid_payload", "config object is required")
		return
	}
	res, err := s.hub.ConfigSet(r.Context(), thing, cfgMap)
	if err != nil {
		writeHubError(w, err)
		return
	}
	writeJSON(w, http.StatusOK, map[string]any{"ok": true, "result": res})
}

