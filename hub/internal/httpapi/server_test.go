package httpapi

import (
	"encoding/json"
	"io"
	"net/http"
	"net/http/httptest"
	"strings"
	"testing"

	"smart_home/hub/internal/config"
	"smart_home/hub/internal/hub"
	"smart_home/hub/web"
)

func testServer(t *testing.T) (*httptest.Server, func()) {
	t.Helper()
	cfg := config.Config{HTTPAddr: ":0"}
	h, err := hub.New(cfg, nil)
	if err != nil {
		t.Fatal(err)
	}
	srv := httptest.NewServer(New(h, cfg, nil).Handler())
	return srv, func() {
		srv.Close()
	}
}

func TestHealthAndStatic(t *testing.T) {
	srv, closeFn := testServer(t)
	defer closeFn()

	resp, err := http.Get(srv.URL + "/api/health")
	if err != nil {
		t.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		t.Fatalf("health status=%d", resp.StatusCode)
	}
	resp2, err := http.Get(srv.URL + "/")
	if err != nil {
		t.Fatal(err)
	}
	defer resp2.Body.Close()
	data, _ := io.ReadAll(resp2.Body)
	if resp2.StatusCode != http.StatusOK || !strings.Contains(string(data), "Smart Home") {
		t.Fatalf("static status=%d body=%q", resp2.StatusCode, string(data[:80]))
	}
}

// TestServiceWorkerServed checks the worker (generated by vite-plugin-pwa) is
// served uncached, so a new build takes over on the next visit.
func TestServiceWorkerServed(t *testing.T) {
	srv, closeFn := testServer(t)
	defer closeFn()

	resp, err := http.Get(srv.URL + "/sw.js")
	if err != nil {
		t.Fatal(err)
	}
	defer resp.Body.Close()
	data, _ := io.ReadAll(resp.Body)
	if resp.StatusCode != http.StatusOK {
		t.Fatalf("sw status=%d", resp.StatusCode)
	}
	if got := resp.Header.Get("Cache-Control"); got != "no-cache" {
		t.Fatalf("sw cache-control=%q", got)
	}
	if !strings.Contains(string(data), "workbox") {
		t.Fatalf("sw does not look like a workbox worker: %q", string(data[:80]))
	}
}

// TestHealthReportsBuildID checks the UI fingerprint is exposed for debugging.
func TestHealthReportsBuildID(t *testing.T) {
	srv, closeFn := testServer(t)
	defer closeFn()

	resp, err := http.Get(srv.URL + "/api/health")
	if err != nil {
		t.Fatal(err)
	}
	defer resp.Body.Close()
	var body struct {
		Build string `json:"build"`
	}
	if err := json.NewDecoder(resp.Body).Decode(&body); err != nil {
		t.Fatal(err)
	}
	if body.Build != web.BuildID() {
		t.Fatalf("health build=%q want %q", body.Build, web.BuildID())
	}
}

// TestAPIIsOpen checks the hub no longer requires a token: it is meant to run
// only behind the LAN/VPN.
func TestAPIIsOpen(t *testing.T) {
	srv, closeFn := testServer(t)
	defer closeFn()

	resp, err := http.Get(srv.URL + "/api/things")
	if err != nil {
		t.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		t.Fatalf("open API status=%d, want 200", resp.StatusCode)
	}
}
